using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Wisdom.Office;
using Wisdom.Office.Core;

namespace Wisdom.Office.Tests
{
    /// <summary>旧二进制格式（OLE2 复合文档、BIFF8、RTF）写出器的回归测试。Regression tests for the legacy binary writers (OLE2 compound file, BIFF8, RTF).</summary>
    internal static partial class Program
    {
        private static void RunCompoundFileWriterTest(string outputDirectory)
        {
            string path = PrepareOutputPath(Path.Combine(outputDirectory, "ole2-writer.bin"));

            byte[] big = BuildPattern(20000, 37);
            byte[] boundary = BuildPattern(4096, 91);
            byte[] belowBoundary = BuildPattern(4095, 53);
            byte[] small = BuildPattern(100, 7);
            byte[] empty = new byte[0];
            byte[] manyMini = BuildPattern(3000, 11);

            CompoundFileWriter writer = new CompoundFileWriter();
            writer.AddStream("Workbook", big);
            writer.AddStream("Exact", boundary);
            writer.AddStream("Below", belowBoundary);
            writer.AddStream("Small", small);
            writer.AddStream("Empty", empty);
            writer.AddStream("ManyMini", manyMini);
            writer.AddStream("中文流名", BuildPattern(64, 3));
            byte[] bytes = writer.ToBytes();
            File.WriteAllBytes(path, bytes);

            Require(bytes.Length > 512 && bytes[0] == 0xD0 && bytes[1] == 0xCF && bytes[7] == 0xE1,
                "compound file header missing");

            CompoundFile parsed = new CompoundFile(bytes);
            List<string> names = new List<string>(parsed.GetStreamNames());
            Require(names.Count == 7, "compound stream count: " + names.Count);
            Require(parsed.HasStream("WORKBOOK"), "compound stream lookup is not case-insensitive");

            RequireEqualBytes(parsed.GetStream("Workbook"), big, "Workbook");
            RequireEqualBytes(parsed.GetStream("Exact"), boundary, "Exact");
            RequireEqualBytes(parsed.GetStream("Below"), belowBoundary, "Below");
            RequireEqualBytes(parsed.GetStream("Small"), small, "Small");
            RequireEqualBytes(parsed.GetStream("ManyMini"), manyMini, "ManyMini");
            RequireEqualBytes(parsed.GetStream("中文流名"), BuildPattern(64, 3), "中文流名");
            Require(parsed.GetStream("Empty").Length == 0, "empty stream should read back empty");
            Require(parsed.TryGetStream("Absent") == null, "missing stream should return null");

            CompoundFileWriter throwing = new CompoundFileWriter();
            RequireThrows(() => throwing.ToBytes(), "empty writer must refuse");
            throwing.AddStream("Sheet1", small);
            RequireThrows(() => throwing.AddStream("SHEET1", small), "duplicate name must be rejected");
            RequireThrows(() => throwing.AddStream(new string('x', 32), small), "over-long name must be rejected");

            // 大量小流会撑出多个迷你扇区与多张 FAT，验证跨扇区的链路仍然正确。
            // Many small streams grow the mini stream over several sectors and FAT tables; the chains must stay right.
            CompoundFileWriter wide = new CompoundFileWriter();
            byte[][] expected = new byte[40][];
            for (int i = 0; i < expected.Length; i++)
            {
                expected[i] = BuildPattern(300 + i * 17, i + 1);
                wide.AddStream("S" + i, expected[i]);
            }
            wide.AddStream("Large", BuildPattern(40000, 5));
            byte[] wideBytes = wide.ToBytes();
            CompoundFile wideFile = new CompoundFile(wideBytes);
            RequireEqualBytes(wideFile.GetStream("Large"), BuildPattern(40000, 5), "Large");
            for (int i = 0; i < expected.Length; i++)
            {
                RequireEqualBytes(wideFile.GetStream("S" + i), expected[i], "S" + i);
            }

            Console.WriteLine("[ole2] writer round trip: " + new FileInfo(path).Length + " bytes, streams=" + names.Count
                + ", wide streams=" + (expected.Length + 1));
        }

        /// <summary>生成可校验的可重复字节序列。Builds a repeatable, verifiable byte pattern.</summary>
        /// <param name="length">字节长度。The byte length.</param>
        /// <param name="seed">种子。The seed.</param>
        /// <returns>生成的字节数组。The generated bytes.</returns>
        private static byte[] BuildPattern(int length, int seed)
        {
            byte[] data = new byte[length];
            int value = seed;
            for (int i = 0; i < length; i++)
            {
                value = (value * 1103515245) + 12345;
                data[i] = (byte)((value >> 16) & 0xFF);
            }
            return data;
        }

        /// <summary>按字节比较两条流；不等时报出首个差异位置。Compares two streams byte by byte and reports the first difference.</summary>
        /// <param name="actual">读回的字节。The bytes read back.</param>
        /// <param name="expected">写入的字节。The bytes written.</param>
        /// <param name="label">流名。The stream label.</param>
        private static void RequireEqualBytes(byte[] actual, byte[] expected, string label)
        {
            Require(actual != null, "compound stream missing: " + label);
            Require(actual.Length == expected.Length,
                "compound stream length " + label + ": " + actual.Length + " != " + expected.Length);
            for (int i = 0; i < expected.Length; i++)
            {
                Require(actual[i] == expected[i], "compound stream body differs at " + label + "[" + i + "]");
            }
        }

        /// <summary>断言动作必须抛出异常。Asserts that the action throws.</summary>
        /// <param name="action">待执行动作。The action to run.</param>
        /// <param name="message">失败提示。The failure message.</param>
        private static void RequireThrows(Action action, string message)
        {
            bool threw = false;
            try
            {
                action();
            }
            catch (Exception)
            {
                threw = true;
            }
            Require(threw, message);
        }
    }
}
